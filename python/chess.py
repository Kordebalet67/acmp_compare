# Но у него возникла проблема определения правильности хода конем, который делает пользователь. 
# Т.е. если пользователь вводит значение «C7-D5», то программа должна определить это как правильный ход, если же введено «E2-E4», то ход неверный. 
# Также нужно проверить корректность записи ввода: если например, введено «D9-N5», то программа должна определить данную запись как ошибочную. 
# Помогите ему осуществить эту проверку!
# Входные данные
# В единственной строке входного файла INPUT.TXT записан текст хода (непустая строка), который указал пользователь. 
# Пользователь не может ввести строку, длиннее 5 символов.
# Выходные данные
# В выходной файл OUTPUT.TXT нужно вывести «YES», если указанный ход конем верный, если же запись корректна 
# (в смысле правильности записи координат), но ход невозможен, то нужно вывести «NO». 
# Если же координаты не определены или заданы некорректно, то вывести сообщение «ERROR». 


def main():
    with open('INPUT.TXT') as input:
        A = input.readline().strip()
        
        with open('OUTPUT.TXT', 'w') as output:
            if len(A) != 5:
                result = "ERROR"
            elif A[2] != '-':
                result = "ERROR"
            else:
                c1, r1 = A[0], A[1]
                c2, r2 = A[3], A[4]

                if c1 not in 'ABCDEFGH' or c2 not in 'ABCDEFGH':
                    result = "ERROR"
                elif r1 not in '12345678' or r2 not in '12345678':
                    result = "ERROR"
                else:
                    dx = abs(ord(c1) - ord(c2))
                    dy = abs(int(r1) - int(r2))

                    if (dx == 1 and dy == 2) or (dx == 2 and dy == 1):
                        result = "YES"
                    else:
                        result = "NO"            
            output.write(result)


if __name__ == '__main__':
    main() 